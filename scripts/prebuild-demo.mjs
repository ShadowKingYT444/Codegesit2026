// Prebuild the practice cases of the demo packs, so a demo track is ready at once (no model calls on install).
// Runs the same buildPracticeCase pipeline as the app. Output: src/demo/prebuilt.js (cleaned cases only, no PII map:
// the demo tickets are fictional). Run with the local claude CLI adapter:  node scripts/prebuild-demo.mjs
import fs from 'node:fs';
import { PACKS } from '../src/demo/packs.js';
import { buildPracticeCase } from '../src/engine/case.js';
import { practiceValue } from '../src/engine/scoring.js';
import { cliLlm } from '../test/claude-cli.mjs';

const out = {};
const jobs = [];
for (const pack of PACKS) {
  const shared = [...pack.kb, ...pack.sop].map((d) => `${d.id} ${d.title || ''}\n${d.body || ''}`).join('\n');
  for (const t of pack.tickets) {
    jobs.push((async () => {
      if (!practiceValue(t, {}).usable) { console.log('skip', t.key); return; }
      for (let attempt = 1; attempt <= 3; attempt++) {
        try {
          const { pc } = await buildPracticeCase(t, cliLlm(), { shared });
          out[`${pack.id}:${t.key}`] = pc;
          console.log('ok', pack.id, t.key, pc.customer.facts.length, 'facts');
          return;
        } catch (e) { console.log('retry', t.key, attempt, e.message.slice(0, 120)); }
      }
    })());
  }
}
await Promise.all(jobs);
const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
fs.writeFileSync(new URL('../src/demo/prebuilt.js', import.meta.url),
  `// Generated by scripts/prebuild-demo.mjs. Cleaned practice cases for the demo packs, keyed "packId:ticketKey".\n` +
  `// A demo track uses these, so it is ready at once with no model calls. Rebuild after you change a pack.\n` +
  `export const PREBUILT = ${JSON.stringify(sorted, null, 1)};\n`);
console.log('wrote', Object.keys(sorted).length, 'cases');
